const localeMap = {
  'en.json': 'en',
  'tr.json': 'tr',
  'de.json': 'de',
  'fr.json': 'fr',
  'es.json': 'es',
  'it.json': 'it',
  'pt.json': 'pt',
  'nl.json': 'nl',
  'ar.json': 'ar',
  'ru.json': 'ru',
  'ja.json': 'ja',
  'ko.json': 'ko',
  'zh.json': 'zh',
  'hi.json': 'hi',
  'gr.json': 'gr',
  'pl.json': 'pl',
  'da.json': 'da',
  'fi.json': 'fi',
  'no.json': 'no',
  'se.json': 'se',
};

let totalAdded = 0;

for (const [filename, langKey] of Object.entries(localeMap)) {
  const filePath = path.join(LOCALES_DIR, filename);
  
  if (!fs.existsSync(filePath)) {
    console.log(`⚠️  Skipping ${filename} (file not found)`);
    continue;
  }

  const raw = fs.readFileSync(filePath, 'utf8');
  const json = JSON.parse(raw);
  
  const newKeys = translations[langKey] || translations['en']; // fallback to English
  let addedCount = 0;
  
  for (const [key, value] of Object.entries(newKeys)) {
    if (!json[key]) {
      json[key] = value;
      addedCount++;
    }
  }

  if (addedCount > 0) {
    fs.writeFileSync(filePath, JSON.stringify(json, null, 2) + '\n', 'utf8');
    console.log(`✅ ${filename}: Added ${addedCount} new keys`);
    totalAdded += addedCount;
  } else {
    console.log(`⏭️  ${filename}: All keys already exist`);
  }
}

console.log(`\n🎯 Done! Total keys added across all locales: ${totalAdded}`);
