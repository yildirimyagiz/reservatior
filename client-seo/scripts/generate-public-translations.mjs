const ALL_KEYS = Object.keys(EN);
const PRIORITY = ['es', 'de', 'fr', 'ru', 'ar', 'pt', 'it', 'zh'];

// Live en.json is the authoritative English reference — placeholder detection
// must compare against its actual values (the hardcoded EN dict may drift).
const REF = JSON.parse(readFileSync(join(LOCALES_DIR, 'en.json'), 'utf-8'));

function main() {
  const localeFiles = [
    'en', 'tr', ...PRIORITY,
    'ja', 'ko', 'hi', 'nl', 'pl', 'sv', 'da', 'fi', 'el', 'no',
  ];
  const fileAlias = { el: 'gr', sv: 'se' };

  for (const locale of localeFiles) {
    const file = fileAlias[locale] || locale;
    const filePath = join(LOCALES_DIR, `${file}.json`);
    const content = JSON.parse(readFileSync(filePath, 'utf-8'));

    let added = 0;
    let changed = 0;

    for (const key of ALL_KEYS) {
      const value = T[locale]?.[key] ?? REF[key] ?? EN[key];
      if (content[key] === undefined) {
        content[key] = value;
        added++;
      } else if (content[key] !== value && locale !== 'en') {
        // Overwrite stale English placeholders with the real (or fallback) value
        const enValue = REF[key] ?? EN[key];
        if (locale === 'tr' && value === enValue) continue; // never overwrite real TR
        if (content[key] === enValue && value !== enValue) {
          content[key] = value;
          changed++;
        }
      }
    }

    writeFileSync(filePath, JSON.stringify(content, null, 2) + '\n', 'utf-8');
    console.log(`  ${locale.padEnd(4)} (${file}.json): +${added} added, ${changed} overwritten`);
  }

  console.log('\n✅ Public page translations generated.');
}

main();
