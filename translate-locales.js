function translateValue(val, lang) {
  if (typeof val !== 'string') return val;
  
  const dict = dictionaries[lang] || simpleDicts[lang];
  if (!dict) return val; // No dictionary, keep EN
  
  let result = val;
  
  // Try exact match first
  if (dict[val]) return dict[val];
  
  // Try pattern replacements
  for (const [pattern, replacement] of Object.entries(dict)) {
    if (result.includes(pattern)) {
      result = result.replace(new RegExp(pattern.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g'), replacement);
    }
  }
  
  return result;
}

