let totalAdded = 0;

for (const file of files) {
  const lang = file.replace('.json', '');
  const localePath = path.join(LOCALES_DIR, file);
  const locale = JSON.parse(fs.readFileSync(localePath, 'utf8'));
  const localeKeys = new Set(Object.keys(locale));
  
  let added = 0;
  for (const key of enKeys) {
    if (!localeKeys.has(key)) {
      locale[key] = translateValue(en[key], lang);
      added++;
    }
  }
  
  if (added > 0) {
    fs.writeFileSync(localePath, JSON.stringify(locale, null, 2) + '\n');
    console.log(`${file}: +${added} keys (total: ${Object.keys(locale).length})`);
    totalAdded += added;
  } else {
    console.log(`${file}: ✅ already complete`);
  }
}

